use std::process::ExitCode;

fn main() -> ExitCode {
    // Peek before consuming: `cli::run` takes the iterator by value.
    if std::env::args_os().len() <= 1 {
        return run_window();
    }

    match cli::run(std::env::args().skip(1)) {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("error: {message}");
            ExitCode::FAILURE
        }
    }
}

/// Render the first frame through `egui`'s paint-callback path, and exit.
///
/// The window draws the scene as an `egui` paint callback inside `egui-wgpu`'s render pass, which
/// no windowless machine can exercise by opening a window. This path runs that same callback
/// against a real `egui-wgpu` renderer with the depth attachment the window configures, so the
/// window's drawing code is verified even where nothing can be displayed.
fn run_egui_screenshot(path: &str) -> ExitCode {
    let scenario = match app::demo_scenario() {
        Ok(scenario) => scenario,
        Err(message) => {
            eprintln!("error: {message}");
            return ExitCode::FAILURE;
        }
    };
    let application = app::App::new(scenario, 30.0);
    match screenshot::screenshot_through_egui(&application, path) {
        Ok(()) => {
            println!("wrote {path}");
            ExitCode::SUCCESS
        }
        Err(message) => {
            eprintln!("error: {message}");
            ExitCode::FAILURE
        }
    }
}

/// Render the interface's panels to a file, and exit.
///
/// The third verification path, for the third layer of the window: the scene image proves the
/// geometry, the `egui` image proves the window's own drawing of it, and this one proves that the
/// panels around it lay out — with the assistant panel open, because that is the panel whose job is
/// to run the engine.
fn run_panel_screenshot(path: &str) -> ExitCode {
    let scenario = match app::demo_scenario() {
        Ok(scenario) => scenario,
        Err(message) => {
            eprintln!("error: {message}");
            return ExitCode::FAILURE;
        }
    };
    let mut application = app::App::new(scenario, 30.0);
    match screenshot::screenshot_panels(&mut application, path) {
        Ok(()) => {
            println!("wrote {path}");
            ExitCode::SUCCESS
        }
        Err(message) => {
            eprintln!("error: {message}");
            ExitCode::FAILURE
        }
    }
}

/// Render the first frame to a file, using an adapter that needs no display, and exit.
///
/// This is a *verification* path, not a feature: it exists so that a build with no window system
/// can still prove that the pipelines create, the shader assembles and the geometry lands on
/// screen. It renders exactly the scene the window would, through the same [`app`] code, into an
/// offscreen texture.
fn run_screenshot(path: &str) -> ExitCode {
    let scenario = match app::demo_scenario() {
        Ok(scenario) => scenario,
        Err(message) => {
            eprintln!("error: {message}");
            return ExitCode::FAILURE;
        }
    };
    let application = app::App::new(scenario, 30.0);
    match screenshot::screenshot(&application, path) {
        Ok(()) => {
            println!("wrote {path}");
            ExitCode::SUCCESS
        }
        Err(message) => {
            eprintln!("error: {message}");
            ExitCode::FAILURE
        }
    }
}

/// Open the desktop window, reporting a failure to start rather than panicking.
///
/// A machine with no display, no GPU adapter or no window system is a normal place to run a
/// binary — in CI, over SSH, inside a container — so the message says what to do instead of
/// printing a backtrace.
fn run_window() -> ExitCode {
    if let Ok(path) = std::env::var("STKCRAFT_SCREENSHOT") {
        return run_screenshot(&path);
    }
    if let Ok(path) = std::env::var("STKCRAFT_SCREENSHOT_EGUI") {
        return run_egui_screenshot(&path);
    }
    if let Ok(path) = std::env::var("STKCRAFT_SCREENSHOT_PANELS") {
        return run_panel_screenshot(&path);
    }
    let scenario = match app::demo_scenario() {
        Ok(scenario) => scenario,
        Err(message) => {
            eprintln!("error: {message}");
            return ExitCode::FAILURE;
        }
    };

    let application = app::App::new(scenario, 30.0);
    match app::run(app::native_options(), application) {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("error: could not open the window: {message}");
            eprintln!("       run `stkcraft --help` for the command line, which needs no display");
            ExitCode::FAILURE
        }
    }
}
