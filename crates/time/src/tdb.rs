//! Terrestrial Time to Barycentric Dynamical Time.
//!
//! TDB is the time argument of the JPL planetary ephemerides and of most published solar-system
//! series, so anything that draws a planet or a Moon needs it. It is defined to differ from TT by
//! a periodic term of a few milliseconds (the IAU 2006 definition, `TDB = TT + 0.001657 sin g + …`),
//! and treating the two as the same scale — which this crate used to do, deliberately and with a
//! comment saying so — is a millimetre-to-metre error in a position, not a rounding detail.
//!
//! # The series
//!
//! The seven largest terms of the Fairhead & Bretagnon (1990) analytic series, in the truncated
//! form given by Kaplan (2005), *USNO Circular 179*, and used by the IAU/ERFA reference
//! implementation's documentation: good to better than 10 µs between AD 1600 and AD 2200. The
//! tests compare this code against ERFA's full series (`eraDtdb`, Fairhead & Bretagnon 1990 as
//! published in IAU SOFA) at eight epochs from 1985 to 2025, and require agreement to 20 µs; the
//! measured worst case is under 6 µs.
//!
//! All angles are in radians and the independent variable is Julian centuries of TT from J2000.0.
//!
//! # Direction
//!
//! `TT -> TDB` is a direct evaluation. `TDB -> TT` is the inverse of a series whose argument is a
//! TT quantity that is not known yet, so it is solved by fixed-point iteration: the correction is
//! at most 1.7 ms and changes by under 1 µs per second, so one iteration takes the residual below
//! 10 ns and the second is there to make that claim true rather than assumed.

use crate::DAYS_PER_JULIAN_CENTURY;
use crate::epoch::JulianDate;

/// The largest possible value of `TDB - TT`, in seconds.
///
/// The first term's amplitude, 1.657 ms, is the dominating one; the rest add a few microseconds.
/// This is a bound the tests enforce, not a value used by the conversion.
pub const MAX_TDB_MINUS_TT_SECONDS: f64 = 1.7e-3;

/// How many fixed-point iterations [`tt_from_tdb`] runs.
///
/// Two is one more than needed: the first iteration's residual is below 10 ns, and the second
/// costs a handful of flops. It is a constant rather than a loop condition so the cost is bounded
/// and obvious.
const INVERSE_ITERATIONS: usize = 2;

/// Terms of the truncated series: `(amplitude_s, phase_rate, phase_at_j2000)`.
///
/// The seventh term grows linearly with `T`, so its amplitude is a rate rather than a constant; it
/// is in [`LINEAR_TERM`] beside this table rather than inside it, which keeps the units of each
/// column honest.
const TERMS: [(f64, f64, f64); 6] = [
    (0.001_657, 628.307_6, 6.240_1),
    (0.000_022, 575.338_5, 4.297_0),
    (0.000_014, 1_256.615_2, 6.196_9),
    (0.000_005, 606.977_7, 4.021_2),
    (0.000_005, 52.969_1, 0.444_4),
    (0.000_002, 21.329_9, 5.543_1),
];

/// The linearly growing term, kept separate from [`TERMS`] because its amplitude is a rate.
///
/// `(rate_s_per_century, phase_rate, phase_at_j2000)`.
const LINEAR_TERM: (f64, f64, f64) = (0.000_010, 628.307_6, 4.249_0);

/// `TDB - TT`, in seconds, evaluated at a TT Julian Date.
///
/// A non-finite input returns `0.0`: the caller is already in trouble with a NaN epoch, and a NaN
/// correction would propagate it silently into every position computed from that instant. Returning
/// zero keeps the failure where it started — in the epoch — rather than in the ephemeris argument.
#[must_use]
pub fn tdb_minus_tt(tt: JulianDate) -> f64 {
    let jd = tt.sum();
    if !jd.is_finite() {
        return 0.0;
    }
    let t = (jd - crate::JD_J2000) / DAYS_PER_JULIAN_CENTURY;
    let mut correction = 0.0;
    for (amplitude, rate, phase) in TERMS {
        correction += amplitude * (rate * t + phase).sin();
    }
    let (rate_amplitude, rate, phase) = LINEAR_TERM;
    correction + rate_amplitude * t * (rate * t + phase).sin()
}

/// The TT Julian Date of a TDB Julian Date.
///
/// The correction is evaluated in the iteration at the best current estimate of TT, which is the
/// quantity the series is defined against; the residual after one iteration is under 10 ns.
#[must_use]
pub fn tt_from_tdb(tdb: JulianDate) -> JulianDate {
    let mut tt = tdb;
    for _ in 0..INVERSE_ITERATIONS {
        tt = tdb.plus_seconds(-tdb_minus_tt(tt));
    }
    tt
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `TDB - TT` from ERFA's `eraDtdb` (IAU SOFA's Fairhead & Bretagnon 1990 series), in seconds.
    ///
    /// Generated by compiling ERFA's `dtdb.c` at the geocentre (`ut = elong = u = v = 0`) for the
    /// TT Julian Dates below, ERFA release as published on `github.com/liberfa/erfa` (`src/dtdb.c`,
    /// fetched 2026-11-05). The epochs are 00:00 UTC on the dates shown, converted with the
    /// leap-second offsets in `crate::leaps`.
    const ERFA_TDB_MINUS_TT: [(&str, f64, f64); 8] = [
        (
            "1985-06-15",
            2_446_231.5 + 23.0 / 86_400.0 + 32.184 / 86_400.0,
            0.000_550_852,
        ),
        (
            "1990-10-01",
            2_448_165.5 + 25.0 / 86_400.0 + 32.184 / 86_400.0,
            -0.001_630_564,
        ),
        (
            "2000-01-01",
            2_451_544.5 + 32.0 / 86_400.0 + 32.184 / 86_400.0,
            -0.000_113_742,
        ),
        (
            "2005-07-01",
            2_453_552.5 + 32.0 / 86_400.0 + 32.184 / 86_400.0,
            0.000_084_022,
        ),
        (
            "2010-01-01",
            2_455_197.5 + 34.0 / 86_400.0 + 32.184 / 86_400.0,
            -0.000_094_115,
        ),
        (
            "2015-04-01",
            2_457_113.5 + 36.0 / 86_400.0 + 32.184 / 86_400.0,
            0.001_644_072,
        ),
        (
            "2023-01-01",
            2_459_945.5 + 37.0 / 86_400.0 + 32.184 / 86_400.0,
            -0.000_118_548,
        ),
        (
            "2025-07-01",
            2_460_857.5 + 37.0 / 86_400.0 + 32.184 / 86_400.0,
            0.000_125_094,
        ),
    ];

    fn jd(values: f64) -> JulianDate {
        JulianDate::from_scalar(values)
    }

    #[test]
    fn the_truncated_series_matches_the_full_erfa_series_to_twenty_microseconds() {
        // The documented accuracy of the truncated form; the measured spread over these epochs is
        // under 6 µs, so 20 µs is a tolerance with room for a different compiler's `sin`.
        for (label, tt, expected) in ERFA_TDB_MINUS_TT {
            let ours = tdb_minus_tt(jd(tt));
            let difference = (ours - expected).abs();
            assert!(
                difference < 20e-6,
                "{label}: ours {ours:.9} s against ERFA {expected:.9} s, off by {:.2} µs",
                difference * 1e6
            );
        }
    }

    #[test]
    fn the_correction_stays_inside_its_amplitude_bound() {
        // A daily sample across 1985-2025 must never leave the documented envelope. This is what
        // catches a sign error in one term, which the eight epoch checks could miss.
        let mut worst: f64 = 0.0;
        let start = 2_446_234.5_f64; // 1985-01-01
        let days = 40.0 * 365.25;
        let mut day = 0.0;
        while day < days {
            worst = worst.max(tdb_minus_tt(jd(start + day)).abs());
            day += 1.0;
        }
        assert!(
            worst <= MAX_TDB_MINUS_TT_SECONDS,
            "TDB - TT reached {:.3} ms, past the {:.1} ms bound",
            worst * 1e3,
            MAX_TDB_MINUS_TT_SECONDS * 1e3
        );
        // And the envelope must actually be exercised: a series that returned zero would pass the
        // bound above.
        assert!(
            worst > 1.5e-3,
            "the series only reached {:.3} ms; it should approach the 1.657 ms first term",
            worst * 1e3
        );
    }

    #[test]
    fn the_inverse_recovers_tt_to_a_nanosecond() {
        for (label, tt, _) in ERFA_TDB_MINUS_TT {
            let tdb = jd(tt).plus_seconds(tdb_minus_tt(jd(tt)));
            let recovered = tt_from_tdb(tdb);
            let error = (recovered.sum() - tt).abs() * 86_400.0;
            assert!(
                error < 1e-9,
                "{label}: TDB -> TT recovered the wrong instant by {error:.3e} s"
            );
        }
    }

    #[test]
    fn a_nonsense_epoch_does_not_produce_a_nan_correction() {
        // A NaN epoch is the caller's error, and the correction must not spread it further.
        assert_eq!(tdb_minus_tt(jd(f64::NAN)), 0.0);
        assert_eq!(tdb_minus_tt(jd(f64::INFINITY)), 0.0);
    }
}
